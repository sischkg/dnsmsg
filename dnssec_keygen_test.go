// These tests generate keys with the real dnssec-keygen tool and import them
// with ReadKeyFile and ReadPrivateKeyFile.  dnssec-keygen is expected to be
// installed in the test environment; the tests are skipped when it is not.

const dnssecKeygenTool = "dnssec-keygen"

// dnssecKeygenZone is the zone passed to dnssec-keygen.  It is the zone used by
// the signing and verification tests, so a generated key can sign the RRsets
// those tests build.
const dnssecKeygenZone = "example.com"

// keygenAlgorithm is one dnssec-keygen algorithm together with the DNSKEY
// algorithm number it produces.
type keygenAlgorithm struct {
	name string
	bits int
	algo uint8
	// sign is false when this package or the Go standard library cannot sign
	// with the algorithm, so the sign and verify checks are skipped.
	sign bool
}

var keygenAlgorithms = []keygenAlgorithm{
	{name: "RSASHA1", bits: 1024, algo: 5, sign: true},
	{name: "NSEC3RSASHA1", bits: 1024, algo: 7, sign: true},
	{name: "RSASHA256", bits: 2048, algo: 8, sign: true},
	{name: "RSASHA512", bits: 2048, algo: 10, sign: true},
	{name: "ECDSAP256SHA256", bits: 256, algo: 13, sign: true},
	{name: "ECDSAP384SHA384", bits: 384, algo: 14, sign: true},
	{name: "Ed25519", bits: 0, algo: 15, sign: true},
	{name: "Ed448", bits: 0, algo: 16, sign: false},
}

// keygenTempDir creates a directory under the repository's tmp/ directory for
// the files generated by dnssec-keygen and removes it when the test ends.
func keygenTempDir(t *testing.T) string {
	t.Helper()

	const tmpDir = "tmp"
	if err := os.MkdirAll(tmpDir, 0o755); err != nil {
		t.Fatalf("cannot create %s: %v", tmpDir, err)
	}
	dir, err := os.MkdirTemp(tmpDir, strings.ReplaceAll(t.Name(), "/", "-")+"-")
	if err != nil {
		t.Fatalf("cannot create a temporary directory in %s: %v", tmpDir, err)
	}
	t.Cleanup(func() {
		if err := os.RemoveAll(dir); err != nil {
			t.Errorf("cannot remove %s: %v", dir, err)
		}
	})
	return dir
}

// dnssecKeygenAvailable reports whether dnssec-keygen can be executed.
func dnssecKeygenAvailable(t *testing.T) bool {
	t.Helper()

	_, err := exec.LookPath(dnssecKeygenTool)
	if err != nil {
		t.Skipf("%s is not installed: %v", dnssecKeygenTool, err)
		return false
	}
	return true
}

// generateKeyWithDnssecKeygen runs dnssec-keygen in dir and returns the base
// name of the files it created, such as "Kexample.com.+008+12345".
func generateKeyWithDnssecKeygen(t *testing.T, dir string, kg keygenAlgorithm, zone string) string {
	t.Helper()

	args := []string{"-a", kg.name, "-n", "ZONE"}
	if kg.bits > 0 {
		args = append(args, "-b", strconv.Itoa(kg.bits))
	}
	args = append(args, zone)

	cmd := exec.Command(dnssecKeygenTool, args...)
	cmd.Dir = dir
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Skipf("%s -a %s failed: %v\n%s", dnssecKeygenTool, kg.name, err, output)
		return ""
	}

	// dnssec-keygen writes K<zone>.+<algorithm>+<key tag>.key and .private.
	matches, err := filepath.Glob(filepath.Join(dir, "*"+zone+".+*+*.key"))
	if err != nil {
		t.Fatalf("glob key files: %v", err)
	}
	if len(matches) != 1 {
		t.Fatalf("%s -a %s created %d key files: %v", dnssecKeygenTool, kg.name, len(matches), matches)
	}
	return strings.TrimSuffix(filepath.Base(matches[0]), ".key")
}

// keyTagFromKeyBaseName returns the key tag dnssec-keygen recorded in the file
// name, which is the third field of "Kname.+algorithm+keytag".
func keyTagFromKeyBaseName(t *testing.T, baseName string) uint16 {
	t.Helper()

	fields := strings.Split(baseName, "+")
	if len(fields) != 3 {
		t.Fatalf("key file base name %q does not have three fields", baseName)
	}
	value, err := strconv.ParseUint(fields[2], 10, 16)
	if err != nil {
		t.Fatalf("key tag in key file base name %q: %v", baseName, err)
	}
	return uint16(value)
}

// dnssecKeyTag computes the key tag of DNSKEY RDATA using the algorithm from
// RFC 4034 Appendix B.
func dnssecKeyTag(rdata []byte) uint16 {
	var ac uint32
	for i, b := range rdata {
		if i&1 == 0 {
			ac += uint32(b) << 8
		} else {
			ac += uint32(b)
		}
	}
	ac += ac >> 16
	return uint16(ac & 0xffff)
}

// dnskeyFromKeyFileText parses the DNSKEY record that dnssec-keygen wrote to a
// .key file.
func dnskeyFromKeyFileText(t *testing.T, text string) RecordDNSKEY {
	t.Helper()

	for _, line := range strings.Split(text, "\n") {
		if !strings.Contains(line, " IN DNSKEY ") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 7 {
			t.Fatalf("DNSKEY line %q has too few fields", line)
		}
		flags, err := strconv.ParseUint(fields[3], 10, 16)
		if err != nil {
			t.Fatalf("DNSKEY flags %q: %v", fields[3], err)
		}
		protocol, err := strconv.ParseUint(fields[4], 10, 8)
		if err != nil {
			t.Fatalf("DNSKEY protocol %q: %v", fields[4], err)
		}
		algorithm, err := strconv.ParseUint(fields[5], 10, 8)
		if err != nil {
			t.Fatalf("DNSKEY algorithm %q: %v", fields[5], err)
		}
		// dnssec-keygen splits long public keys into space separated chunks.
		encoded := strings.Join(fields[6:], "")
		material, err := base64.StdEncoding.DecodeString(encoded)
		if err != nil {
			t.Fatalf("DNSKEY public key %q: %v", encoded, err)
		}
		return NewRecordDNSKEY(uint16(flags), uint8(protocol), uint8(algorithm), material)
	}

	t.Fatalf("no DNSKEY record found in key file:\n%s", text)
	return RecordDNSKEY{}
}

// privateKeyParam returns one of the named private key parameters imported by
// ReadPrivateKeyFile.  Names are matched case insensitively, because
// dnssec-keygen names the private key material differently for each algorithm.
func privateKeyParam(t *testing.T, key *DNSSECKey, names ...string) []byte {
	t.Helper()

	for _, want := range names {
		for name, value := range key.PrivateParams {
			if strings.EqualFold(name, want) {
				return value
			}
		}
	}
	t.Fatalf("private key for algorithm %d has none of %v (parameters: %v)", key.Algorithm, names, key.PrivateParams)
	return nil
}

// signerFromPrivateKeyFile builds a crypto.Signer from the private key material
// imported by ReadPrivateKeyFile, so that the imported key can sign an RRset.
// The public key of the returned signer is derived from the private key
// material, because a .private file does not contain the public key.
func signerFromPrivateKeyFile(t *testing.T, key *DNSSECKey) crypto.Signer {
	t.Helper()

	switch key.Algorithm {
	case 5, 7, 8, 10:
		rsaKey := &rsa.PrivateKey{
			PublicKey: rsa.PublicKey{
				N: new(big.Int).SetBytes(privateKeyParam(t, key, "Modulus")),
				// dnssec-keygen encodes the exponent as base64 octets ("AQAB").
				E: int(new(big.Int).SetBytes(privateKeyParam(t, key, "PublicExponent")).Int64()),
			},
			D: new(big.Int).SetBytes(privateKeyParam(t, key, "PrivateExponent")),
			Primes: []*big.Int{
				new(big.Int).SetBytes(privateKeyParam(t, key, "Prime1")),
				new(big.Int).SetBytes(privateKeyParam(t, key, "Prime2")),
			},
		}
		rsaKey.Precompute()
		if err := rsaKey.Validate(); err != nil {
			t.Fatalf("RSA private key imported from a private key file is invalid: %v", err)
		}
		return rsaKey

	case 13, 14:
		var curve elliptic.Curve = elliptic.P256()
		if key.Algorithm == 14 {
			curve = elliptic.P384()
		}
		d := new(big.Int).SetBytes(privateKeyParam(t, key, "PrivateKey"))
		// The public point is derived from the private scalar, because the
		// private key file does not contain it.
		x, y := curve.ScalarBaseMult(d.Bytes())
		return &ecdsa.PrivateKey{
			PublicKey: ecdsa.PublicKey{Curve: curve, X: x, Y: y},
			D:         d,
		}

	case 15:
		seed := privateKeyParam(t, key, "PrivateKey")
		if len(seed) != ed25519.SeedSize {
			t.Fatalf("Ed25519 private key is %d bytes, want %d", len(seed), ed25519.SeedSize)
		}
		return ed25519.NewKeyFromSeed(seed)
	}

	t.Fatalf("cannot build a signer for algorithm %d", key.Algorithm)
	return nil
}

// TestReadKeyFile_GeneratedByDnssecKeygen imports keys produced by the real
// dnssec-keygen tool and checks them against the .key and .private files that
// the tool wrote.
func TestReadKeyFile_GeneratedByDnssecKeygen(t *testing.T) {
	if !dnssecKeygenAvailable(t) {
		return
	}

	for _, kg := range keygenAlgorithms {
		t.Run(kg.name, func(t *testing.T) {
			dir := keygenTempDir(t)
			baseName := generateKeyWithDnssecKeygen(t, dir, kg, dnssecKeygenZone)
			keyPath := filepath.Join(dir, baseName+".key")
			privatePath := filepath.Join(dir, baseName+".private")
			t.Logf("%s created %s.key and %s.private", dnssecKeygenTool, baseName, baseName)

			// The .key file is imported with ReadKeyFile.
			key, err := ReadKeyFile(keyPath)
			if err != nil {
				t.Fatalf("ReadKeyFile(%s): %v", keyPath, err)
			}

			wantName := testDomainName(t, dnssecKeygenZone+".")
			if !key.Name.Equal(wantName) {
				t.Errorf("imported name = %s, want %s", key.Name.String(), wantName.String())
			}
			// dnssec-keygen -n ZONE creates a zone key, not a secure entry
			// point (RFC 4034 Section 2.1.1).
			if key.Flags != 256 {
				t.Errorf("imported flags = %d, want 256", key.Flags)
			}
			if key.Protocol != 3 {
				t.Errorf("imported protocol = %d, want 3", key.Protocol)
			}
			if key.Algorithm != kg.algo {
				t.Errorf("imported algorithm = %d, want %d (%s)", key.Algorithm, kg.algo, kg.name)
			}
			if key.PrivateParams != nil {
				t.Errorf("ReadKeyFile(%s) returned private key parameters: %v", keyPath, key.PrivateParams)
			}

			// The key tag of the imported key must be the one dnssec-keygen
			// recorded in the file name.
			dnskey := key.ToDNSKEY()
			wantTag := keyTagFromKeyBaseName(t, baseName)
			if got := dnssecKeyTag(dnskey.CanonicalWireFormat()); got != wantTag {
				t.Errorf("key tag = %d, want %d from the file name %s", got, wantTag, baseName)
			}

			// The imported key must be the DNSKEY record written to the .key
			// file.
			keyFileData, err := os.ReadFile(keyPath)
			if err != nil {
				t.Fatalf("read %s: %v", keyPath, err)
			}
			wantDNSKEY := dnskeyFromKeyFileText(t, string(keyFileData))
			if !bytes.Equal(dnskey.CanonicalWireFormat(), wantDNSKEY.CanonicalWireFormat()) {
				t.Errorf("imported DNSKEY =\n%s\nwant\n%s", dnskey.String(), wantDNSKEY.String())
			}

			// The .private file is imported with ReadPrivateKeyFile.  It carries
			// the algorithm and the private key parameters, but a .private file
			// has no name, flags, protocol or public key.
			withPrivate, err := ReadPrivateKeyFile(privatePath)
			if err != nil {
				t.Fatalf("ReadPrivateKeyFile(%s): %v", privatePath, err)
			}
			if withPrivate.Algorithm != kg.algo {
				t.Errorf("private key algorithm = %d, want %d (%s)", withPrivate.Algorithm, kg.algo, kg.name)
			}
			if len(withPrivate.PrivateParams) == 0 {
				t.Fatalf("ReadPrivateKeyFile(%s) returned no private key parameters", privatePath)
			}
			if len(withPrivate.PrivateKey) == 0 {
				t.Errorf("ReadPrivateKeyFile(%s) returned no private key material", privatePath)
			}
			if len(withPrivate.PublicKey) != 0 {
				t.Errorf("ReadPrivateKeyFile(%s) returned public key material: %s",
					privatePath, base64.StdEncoding.EncodeToString(withPrivate.PublicKey))
			}

			if !kg.sign {
				t.Logf("algorithm %d (%s) cannot be used for signing with the Go standard library: skipping the sign and verify check",
					kg.algo, kg.name)
				return
			}

			// The private key material must belong to the public key imported
			// from the .key file: the public key it derives must be the one the
			// .key file holds, and a signature made with it must verify with
			// that public key.
			signer := signerFromPrivateKeyFile(t, withPrivate)
			material := dnskeyMaterialFromPublicKey(t, signer.Public())
			// The public key imported from the .key file is decoded with the
			// library and encoded again the same way, so that the comparison does
			// not depend on which of the two legal RSA exponent length encodings
			// dnssec-keygen happened to use.
			importedPub, err := NewDNSSECPublicKey(key.Algorithm, key.PublicKey)
			if err != nil {
				t.Fatalf("NewDNSSECPublicKey(algorithm %d): %v", key.Algorithm, err)
			}
			wantMaterial := dnskeyMaterialFromPublicKey(t, importedPub)
			if !bytes.Equal(material, wantMaterial) {
				t.Errorf("public key derived from the private key material = %s, want %s",
					base64.StdEncoding.EncodeToString(material),
					base64.StdEncoding.EncodeToString(wantMaterial))
			}

			rs := buildVerifyTestRRSet(t)
			rrsig, err := SignRRSet(&rs, signer, kg.algo, wantTag, key.Name, testInception, testExpiration)
			if err != nil {
				t.Fatalf("SignRRSet with the private key imported from %s: %v", privatePath, err)
			}
			if rrsig.KeyTag != wantTag {
				t.Errorf("RRSIG key tag = %d, want %d", rrsig.KeyTag, wantTag)
			}
			if !rrsig.SignersName.Equal(key.Name) {
				t.Errorf("RRSIG signer's name = %s, want %s", rrsig.SignersName.String(), key.Name.String())
			}
			if err := VerifyRRSet(&rs, rrsig, signer.Public(), testVerifyTime); err != nil {
				t.Errorf("VerifyRRSet with the public key derived from %s: %v", privatePath, err)
			}
			if err := VerifyRRSetWithDNSKEY(&rs, rrsig, &dnskey, testVerifyTime); err != nil {
				t.Errorf("VerifyRRSetWithDNSKEY with the DNSKEY imported from %s: %v", keyPath, err)
			}
		})
	}
}

// TestReadPrivateKeyFile_GeneratedByDnssecKeygen_WireRoundTrip signs an RRset
// with a key generated by dnssec-keygen, encodes the DNSKEY and the resulting
// RRSIG as resource records, decodes them again, and verifies the decoded pair.
func TestReadPrivateKeyFile_GeneratedByDnssecKeygen_WireRoundTrip(t *testing.T) {
	if !dnssecKeygenAvailable(t) {
		return
	}

	for _, kg := range keygenAlgorithms {
		if !kg.sign {
			continue
		}
		t.Run(kg.name, func(t *testing.T) {
			dir := keygenTempDir(t)
			baseName := generateKeyWithDnssecKeygen(t, dir, kg, dnssecKeygenZone)

			key, err := ReadKeyFile(filepath.Join(dir, baseName+".key"))
			if err != nil {
				t.Fatalf("ReadKeyFile: %v", err)
			}
			withPrivate, err := ReadPrivateKeyFile(filepath.Join(dir, baseName+".private"))
			if err != nil {
				t.Fatalf("ReadPrivateKeyFile: %v", err)
			}
			signer := signerFromPrivateKeyFile(t, withPrivate)
			keyTag := keyTagFromKeyBaseName(t, baseName)

			rs := buildVerifyTestRRSet(t)
			rrsig, err := SignRRSet(&rs, signer, kg.algo, keyTag, key.Name, testInception, testExpiration)
			if err != nil {
				t.Fatalf("SignRRSet with the private key imported from %s: %v", baseName+".private", err)
			}

			// Encode the DNSKEY and the RRSIG as resource records.
			dnskey := key.ToDNSKEY()
			records := []ResourceRecord{
				{Name: key.Name, Class: CLASS_IN, Type: TYPE_DNSKEY, TTL: 3600, RData: dnskey},
				{Name: rs.Name, Class: rs.Class, Type: TYPE_RRSIG, TTL: rs.TTL, RData: rrsig},
			}
			msg := WireFormat{}
			db := NewNameCompressionDB()
			offsets := make([]uint32, 0, len(records))
			for _, rr := range records {
				offsets = append(offsets, msg.Size())
				msgSize := AppendResourceRecord(&msg, rr, db)
				if msgSize != msg.Size()-offsets[len(offsets)-1] {
					t.Fatalf("AppendResourceRecord(%s) reported %d bytes, the message grew by %d bytes",
						rr.Type, msgSize, msg.Size()-offsets[len(offsets)-1])
				}
			}

			// Decode the records again and compare them with the records that
			// were encoded.
			var gotDNSKEY RecordDNSKEY
			var gotRRSIG RecordRRSIG
			for i, rr := range records {
				got, end, err := ParseResourceRecord(msg, offsets[i])
				if err != nil {
					t.Fatalf("ParseResourceRecord(%s) at offset %d: %v", rr.Type, offsets[i], err)
				}
				wantEnd := msg.Size()
				if i+1 < len(offsets) {
					wantEnd = offsets[i+1]
				}
				if end != wantEnd {
					t.Errorf("ParseResourceRecord(%s) ended at offset %d, want %d", rr.Type, end, wantEnd)
				}
				if !got.Name.Equal(rr.Name) {
					t.Errorf("decoded owner name = %s, want %s", got.Name.String(), rr.Name.String())
				}
				if got.Class != rr.Class || got.Type != rr.Type || got.TTL != rr.TTL {
					t.Errorf("decoded class/type/TTL = %d/%s/%d, want %d/%s/%d",
						got.Class, got.Type, got.TTL, rr.Class, rr.Type, rr.TTL)
				}
				switch want := rr.RData.(type) {
				case RecordDNSKEY:
					gotDNSKEY, err = decodedRecordDNSKEY(t, got)
					if err != nil {
						t.Fatalf("decoded DNSKEY: %v", err)
					}
					if !bytes.Equal(gotDNSKEY.CanonicalWireFormat(), want.CanonicalWireFormat()) {
						t.Errorf("decoded DNSKEY =\n%s\nwant\n%s", gotDNSKEY.String(), want.String())
					}
				case *RecordRRSIG:
					gotRRSIG, err = decodedRecordRRSIG(t, got)
					if err != nil {
						t.Fatalf("decoded RRSIG: %v", err)
					}
					if !bytes.Equal(gotRRSIG.CanonicalWireFormat(), want.CanonicalWireFormat()) {
						t.Errorf("decoded RRSIG =\n%s\nwant\n%s", gotRRSIG.String(), want.String())
					}
				}
			}

			// The decoded records must still verify against the RRset that was
			// signed.
			if err := VerifyRRSetWithDNSKEY(&rs, &gotRRSIG, &gotDNSKEY, testVerifyTime); err != nil {
				t.Errorf("VerifyRRSetWithDNSKEY with the decoded RRSIG and DNSKEY: %v", err)
			}
		})
	}
}

// decodedRecordDNSKEY returns the DNSKEY RDATA of a decoded resource record.
func decodedRecordDNSKEY(t *testing.T, rr ResourceRecord) (RecordDNSKEY, error) {
	t.Helper()

	dnskey, ok := rr.RData.(RecordDNSKEY)
	if !ok {
		return RecordDNSKEY{}, fmt.Errorf("decoded RDATA is %T, want RecordDNSKEY", rr.RData)
	}
	return dnskey, nil
}

// decodedRecordRRSIG returns the RRSIG RDATA of a decoded resource record.
func decodedRecordRRSIG(t *testing.T, rr ResourceRecord) (RecordRRSIG, error) {
	t.Helper()

	rrsig, ok := rr.RData.(RecordRRSIG)
	if !ok {
		return RecordRRSIG{}, fmt.Errorf("decoded RDATA is %T, want RecordRRSIG", rr.RData)
	}
	return rrsig, nil
}
